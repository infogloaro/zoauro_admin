// Super Admin account dialogs (D148, D102/D103): add with a temporary password typed or generated by the creator (shared
// in person, never emailed), suspend or reactivate, delete. Every write asks for the password and a code (STRONG) and
// a reason of at least 5 characters, kept in the audit trail. The API refuses oneself and the last active Super Admin.

export const REASON_MIN = 5;

/** The API's refusals in plain words (SELF, LAST_SUPER_ADMIN, an email already in use). */
export function superAdminProblem(err: unknown): string {
  if (!isApiError(err)) return TRY_AGAIN;
  const detail = err.details.map((d) => d.issue).join(' ');
  if (err.code === 'CONFLICT' && /LAST_SUPER_ADMIN/.test(`${detail} ${err.message}`))
    return 'This is the last active Super Admin. Add or reactivate another one first.';
  if (/LAST_PRIMARY/.test(detail))
    return 'This is the last primary Super Admin. Make another one primary first.';
  if (/PRIMARY_ONLY/.test(detail)) return 'Only a primary Super Admin can manage Super Admins.';
  if (/PRIMARY_HOLDS_ALL/.test(detail)) return 'A primary Super Admin holds every area already.';
  if (err.code === 'CONFLICT' && /SELF/.test(`${detail} ${err.message}`))
    return 'You cannot do this to your own account.';
  if (err.code === 'CONFLICT') return 'An account with this email already exists.';
  return err.message || TRY_AGAIN;
}

type Issues = readonly { path: readonly PropertyKey[]; message: string }[];
const byField = (issues: Issues) => {
  const out: Record<string, string> = {};
  for (const i of issues) {
    const k = String(i.path[0] ?? 'form');
    out[k] ??=
      k === 'email'
        ? 'Enter a valid email address.'
        : k === 'phone'
          ? 'Enter an Indian mobile number.'
          : k === 'temporaryPassword'
            ? `Use at least ${PASSWORD_MIN_LENGTH} characters that are not a common password.`
            : k === 'reason'
              ? `Give a reason of at least ${REASON_MIN} characters.`
              : i.message;
  }
  return out;
};

export function AddSuperAdminDialog({
  open,
  catalogue,
  onClose,
}: {
  open: boolean;
  /** D178: the areas the new (non-primary) Super Admin may be given */
  catalogue: Catalogue;
  onClose: () => void;
}) {
  const client = useApiClient();
  const invalidate = useInvalidateSuperAdmins();
  const { toast } = useToast();
  const { guarded, dialog } = useReauthGuard();
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [phone, setPhone] = useState('');
  const [password, setPassword] = useState('');
  const [reason, setReason] = useState('');
  const [areas, setAreas] = useState<string[]>([]);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (!open) return;
    setAreas([]);
    setName('');
    setEmail('');
    setPhone('');
    setPassword('');
    setReason('');
    setErrors({});
  }, [open]);

  async function submit() {
    setErrors({});
    const parsed = createSuperAdminSchema.safeParse({
      name: name.trim(),
      email: email.trim(),
      ...(phone.trim() ? { phone: phone.trim() } : {}),
      temporaryPassword: password,
      areas,
      reason: reason.trim(),
    });
    if (!parsed.success) {
      setErrors(byField(parsed.error.issues));
      return;
    }
    setBusy(true);
    try {
      await guarded(`Add ${parsed.data.name} as a Super Admin`, 'STRONG', async () => {
        await client.post('/super-admins', { body: parsed.data });
      });
      toast({
        title: 'Super Admin added',
        description:
          'Share the temporary password with them directly. They change it at the first sign-in.',
      });
      await invalidate();
      onClose();
    } catch (err) {
      if (err instanceof ReauthCancelled) return;
      if (isApiError(err, 'VALIDATION_ERROR') && err.details.length > 0)
        setErrors(byField(err.details.map((d) => ({ path: [d.field], message: d.issue }))));
      else setErrors({ form: superAdminProblem(err) });
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <Dialog open={open} onOpenChange={(o) => !o && !busy && onClose()}>
        <DialogContent className="max-h-[90vh] max-w-2xl overflow-y-auto">
          <div>
            <DialogTitle>Add a Super Admin</DialogTitle>
            <DialogDescription>
              A Super Admin works across every zone. They sign in with this temporary password, must
              change it, then set up 2-step. Asks for your password and a code.
            </DialogDescription>
          </div>
          <form
            noValidate
            className="flex flex-col gap-4"
            onSubmit={(e) => {
              e.preventDefault();
              if (!busy) void submit();
            }}
          >
            {errors['form'] ? <FormAlert>{errors['form']}</FormAlert> : null}
            <FormField label="Full name" error={errors['name']}>
              <Input
                value={name}
                maxLength={MEMBER_NAME_MAX}
                onChange={(e) => setName(e.target.value)}
              />
            </FormField>
            <FormField label="Email" error={errors['email']} hint="Their sign-in name">
              <Input
                type="email"
                autoComplete="off"
                value={email}
                onChange={(e) => setEmail(e.target.value)}
              />
            </FormField>
            <FormField
              label="Mobile (optional)"
              error={errors['phone']}
              hint="Indian mobile, e.g. 98765 43210"
            >
              <Input inputMode="tel" value={phone} onChange={(e) => setPhone(e.target.value)} />
            </FormField>
            <div className="flex flex-col gap-1.5">
              <FormField
                label="Temporary password"
                error={errors['temporaryPassword']}
                hint={`At least ${PASSWORD_MIN_LENGTH} characters. Give it to them in person or by phone, never by email.`}
              >
                <PasswordInput
                  autoComplete="new-password"
                  value={password}
                  onChange={(e) => setPassword(e.target.value)}
                />
              </FormField>
              <Button
                variant="ghost"
                size="sm"
                className="self-start"
                onClick={() => setPassword(generatePassword())}
              >
                <Wand2 aria-hidden className="size-3.5" /> Generate a strong password
              </Button>
            </div>
            <AreaPicker catalogue={catalogue} value={areas} onChange={setAreas} />
            <FormField
              label="Reason"
              error={errors['reason']}
              hint={`Kept in the audit trail. At least ${REASON_MIN} characters.`}
            >
              <textarea
                className={inputClass('min-h-16 py-2')}
                maxLength={500}
                value={reason}
                onChange={(e) => setReason(e.target.value)}
              />
            </FormField>
            <div className="flex justify-end gap-2 border-t border-line pt-4">
              <Button variant="secondary" onClick={onClose} disabled={busy}>
                Cancel
              </Button>
              <Button type="submit" disabled={busy}>
                {busy ? 'Adding…' : 'Add Super Admin'}
              </Button>
            </div>
          </form>
        </DialogContent>
      </Dialog>
      {dialog}
    </>
  );
}

export type SuperAdminAction = 'suspend' | 'reactivate' | 'delete';

const COPY: Record<
  SuperAdminAction,
  { title: string; body: string; confirm: string; danger: boolean }
> = {
  suspend: {
    title: 'Suspend',
    body: 'They can no longer sign in, and every open session ends now. Reactivate them later if needed.',
    confirm: 'Suspend',
    danger: true,
  },
  reactivate: {
    title: 'Reactivate',
    body: 'They can sign in again with their current password and 2-step.',
    confirm: 'Reactivate',
    danger: false,
  },
  delete: {
    title: 'Remove',
    body: 'The account is removed (kept in the history) and every open session ends now.',
    confirm: 'Remove Super Admin',
    danger: true,
  },
};

export function SuperAdminActionDialog({
  target,
  action,
  onClose,
}: {
  target: SuperAdmin;
  /** null = closed */
  action: SuperAdminAction | null;
  onClose: () => void;
}) {
  const client = useApiClient();
  const invalidate = useInvalidateSuperAdmins();
  const { toast } = useToast();
  const { guarded, dialog } = useReauthGuard();
  const [reason, setReason] = useState('');
  const [alert, setAlert] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    setReason('');
    setAlert(null);
  }, [action]);

  if (!action) return dialog;
  const copy = COPY[action];
  const ok = reason.trim().length >= REASON_MIN;

  async function run() {
    if (!action) return;
    setAlert(null);
    setBusy(true);
    try {
      await guarded(`${copy.title} ${target.name}`, 'STRONG', async () => {
        const params = { id: target.id };
        if (action === 'delete') {
          const body = deleteSuperAdminSchema.parse({ reason: reason.trim() });
          await client.delete('/super-admins/{id}', { params, body });
        } else {
          const body = superAdminStatusSchema.parse({
            status: action === 'suspend' ? 'SUSPENDED' : 'ACTIVE',
            reason: reason.trim(),
          });
          await client.patch('/super-admins/{id}/status', { params, body });
        }
      });
      toast({
        title:
          action === 'delete'
            ? `${target.name} was removed`
            : action === 'suspend'
              ? `${target.name} is suspended`
              : `${target.name} is active again`,
      });
      await invalidate();
      onClose();
    } catch (err) {
      if (err instanceof ReauthCancelled) return;
      setAlert(superAdminProblem(err));
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <Dialog open onOpenChange={(o) => !o && !busy && onClose()}>
        <DialogContent>
          <div>
            <DialogTitle>
              {copy.title} {target.name}?
            </DialogTitle>
            <DialogDescription>{copy.body} Asks for your password and a code.</DialogDescription>
          </div>
          {alert ? <FormAlert>{alert}</FormAlert> : null}
          <FormField
            label="Reason"
            hint={`Kept in the audit trail. At least ${REASON_MIN} characters.`}
          >
            <textarea
              className={inputClass('min-h-20 py-2')}
              maxLength={500}
              value={reason}
              onChange={(e) => setReason(e.target.value)}
            />
          </FormField>
          <div className="flex justify-end gap-2">
            <Button variant="secondary" onClick={onClose} disabled={busy}>
              Cancel
            </Button>
            <Button
              variant={copy.danger ? 'danger' : 'primary'}
              onClick={() => void run()}
              disabled={busy || !ok}
            >
              {copy.confirm}
            </Button>
          </div>
        </DialogContent>
      </Dialog>
      {dialog}
    </>
  );
}
